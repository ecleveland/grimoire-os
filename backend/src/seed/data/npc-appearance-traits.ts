export const npcAppearanceTraits: NpcAppearanceTraitEntry[] = (() => {
  const out: NpcAppearanceTraitEntry[] = [];
  for (const [race, byCat] of Object.entries(traitsByRace)) {
    for (const category of NPC_APPEARANCE_CATEGORIES) {
      for (const trait of byCat[category]) {
        out.push({ race, category, trait });
      }
    }
  }
  return out;
})();
